-- =============================================================================
-- Schema ERP semplificato per Oracle Database (scritto per 19c+ / 23ai Free)
-- Ispirato alle tabelle Oracle EBS R12 Inventory / Purchasing: SOLO le colonne
-- necessarie alla demo, non e' lo schema EBS reale.
-- Ogni istruzione termina con una riga contenente solo "/" (compatibile SQL*Plus/SQLcl
-- e con lo splitter usato da `python -m erpfhir init-db`).
-- =============================================================================

CREATE TABLE po_vendors (
    vendor_id        NUMBER        PRIMARY KEY,
    vendor_name      VARCHAR2(240) NOT NULL,
    vat_number       VARCHAR2(30)
)
/
CREATE TABLE mtl_secondary_inventories (
    organization_id    NUMBER       NOT NULL,
    subinventory_code  VARCHAR2(10) NOT NULL,
    description        VARCHAR2(240),
    fhir_location_id   VARCHAR2(64),
    CONSTRAINT mtl_secinv_pk PRIMARY KEY (organization_id, subinventory_code)
)
/
CREATE TABLE mtl_system_items_b (
    inventory_item_id         NUMBER        PRIMARY KEY,
    organization_id           NUMBER        NOT NULL,
    segment1                  VARCHAR2(40)  NOT NULL CONSTRAINT mtl_items_seg1_uk UNIQUE,
    description               VARCHAR2(240) NOT NULL,
    primary_uom_code          VARCHAR2(3)   DEFAULT 'PZ' NOT NULL,
    gtin                      VARCHAR2(14)  CONSTRAINT mtl_items_gtin_uk UNIQUE,
    manufacturer_name         VARCHAR2(240),
    stock_enabled_flag        VARCHAR2(1)   NOT NULL CONSTRAINT mtl_items_stock_ck CHECK (stock_enabled_flag IN ('Y','N')),
    consigned_vendor_id       NUMBER        REFERENCES po_vendors (vendor_id),
    last_contract_price       NUMBER,
    fhir_device_definition_id VARCHAR2(64),
    last_fhir_sync_date       DATE
)
/
CREATE TABLE mtl_onhand_quantities_detail (
    organization_id      NUMBER       NOT NULL,
    inventory_item_id    NUMBER       NOT NULL REFERENCES mtl_system_items_b (inventory_item_id),
    subinventory_code    VARCHAR2(10) NOT NULL,
    lot_number           VARCHAR2(80) NOT NULL,
    transaction_quantity NUMBER       NOT NULL,
    CONSTRAINT mtl_onhand_pk PRIMARY KEY (organization_id, inventory_item_id, subinventory_code, lot_number)
)
/
CREATE TABLE mtl_material_transactions (
    transaction_id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id         NUMBER        NOT NULL,
    inventory_item_id       NUMBER        NOT NULL,
    subinventory_code       VARCHAR2(10)  NOT NULL,
    lot_number              VARCHAR2(80),
    transaction_quantity    NUMBER        NOT NULL,
    transaction_type_name   VARCHAR2(80)  NOT NULL,
    transaction_reference   VARCHAR2(240),
    transaction_date        DATE          NOT NULL
)
/
CREATE TABLE po_requisitions_interface_all (
    interface_id                NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    interface_source_code       VARCHAR2(25)  NOT NULL,
    requisition_type            VARCHAR2(25)  NOT NULL,
    item_id                     NUMBER        NOT NULL,
    quantity                    NUMBER        NOT NULL,
    unit_price                  NUMBER,
    suggested_vendor_id         NUMBER,
    destination_organization_id NUMBER        NOT NULL,
    destination_subinventory    VARCHAR2(10),
    lot_number                  VARCHAR2(80),
    note_to_buyer               VARCHAR2(480),
    source_reference            VARCHAR2(240) NOT NULL CONSTRAINT po_req_iface_src_uk UNIQUE,
    process_flag                VARCHAR2(30)  DEFAULT 'PENDING' NOT NULL,
    creation_date               DATE          NOT NULL
)
/
CREATE TABLE xx_fhir_consumption_stg (
    charge_item_id   VARCHAR2(64)  PRIMARY KEY,
    gtin             VARCHAR2(14),
    lot_number       VARCHAR2(80),
    quantity         NUMBER,
    location_id      VARCHAR2(64),
    encounter_ref    VARCHAR2(240),
    procedure_ref    VARCHAR2(240),
    occurrence_date  VARCHAR2(40),
    status           VARCHAR2(10)  DEFAULT 'NEW' NOT NULL
                     CONSTRAINT xx_fhir_stg_status_ck CHECK (status IN ('NEW','PROCESSED','ERROR')),
    error_message    VARCHAR2(240),
    load_date        DATE          NOT NULL,
    processed_date   DATE
)
/
CREATE TABLE xx_fhir_sync_control (
    flow_name      VARCHAR2(40) PRIMARY KEY,
    last_run_date  VARCHAR2(40)
)
/
